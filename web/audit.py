from playwright.sync_api import sync_playwright
import pathlib,os
u='file://'+str(pathlib.Path('dist-single/index.html').resolve())
os.makedirs('audit',exist_ok=True)
def go(pg,h): pg.evaluate(f"location.hash='{h}'");pg.wait_for_timeout(400)
def run(pg,pre):
    pg.goto(u);pg.wait_for_timeout(800)
    pg.screenshot(path=f'audit/{pre}01-feed.png')
    pg.mouse.wheel(0,900);pg.wait_for_timeout(600);pg.screenshot(path=f'audit/{pre}02-feed2.png')
    go(pg,'offer-o1');pg.screenshot(path=f'audit/{pre}03-offer.png',full_page=True)
    pg.evaluate("document.querySelector('main .overflow-y-auto').scrollTop=99999");pg.wait_for_timeout(200);pg.screenshot(path=f'audit/{pre}04-offer-bottom.png')
    go(pg,'product-p6');pg.screenshot(path=f'audit/{pre}05-product.png')
    go(pg,'chats');pg.screenshot(path=f'audit/{pre}06-chats.png')
    go(pg,'chats-d1');pg.screenshot(path=f'audit/{pre}07-chat.png')
    go(pg,'me');pg.screenshot(path=f'audit/{pre}08-profile.png')
    pg.click('text=Demo:');pg.wait_for_timeout(300);pg.screenshot(path=f'audit/{pre}09-profile-seller.png')
    go(pg,'offer-o1');pg.screenshot(path=f'audit/{pre}10-offer-owner.png')
    go(pg,'chats-d2');pg.screenshot(path=f'audit/{pre}11-chat-seller.png')
    go(pg,'plus');pg.screenshot(path=f'audit/{pre}12-create.png')
    pg.click('text=Post an offer');pg.wait_for_timeout(300);pg.screenshot(path=f'audit/{pre}13-step1.png')
    pg.click('text=Continue');pg.wait_for_timeout(300);pg.screenshot(path=f'audit/{pre}14-step2.png')
    pg.click('text=Add a new product');pg.wait_for_timeout(300);pg.screenshot(path=f'audit/{pre}15-newprod.png')
    pg.click('text=Back');pg.wait_for_timeout(300);pg.click('text=Scotch Bonnet');pg.click('text=Continue');pg.wait_for_timeout(300)
    pg.click('text=Continue');pg.wait_for_timeout(300);pg.screenshot(path=f'audit/{pre}16-budget.png')
    pg.fill('input[placeholder="1,000"]','1000');pg.click('text=Continue');pg.wait_for_timeout(300);pg.screenshot(path=f'audit/{pre}17-review.png')
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox'])
    run(b.new_page(viewport={'width':390,'height':844}),'m')
    run(b.new_page(viewport={'width':1440,'height':900}),'d')
